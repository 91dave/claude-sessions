package transcript

import (
	"strings"
	"testing"
)

const caveat = `{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}`

const clearCommand = `{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"}}`

func parse(t *testing.T, lines ...string) Session {
	t.Helper()
	s, err := Parse(strings.NewReader(strings.Join(lines, "\n")))
	if err != nil {
		t.Fatalf("Parse: %v", err)
	}
	return s
}

func TestHasTurns(t *testing.T) {
	cases := []struct {
		name  string
		want  bool
		lines []string
	}{
		{"a /login-only session has none", false, []string{
			`{"type":"mode"}`,
			caveat,
			`{"type":"user","message":{"role":"user","content":"<command-name>/login</command-name>\n            <command-message>login</command-message>\n            <command-args></command-args>"}}`,
			`{"type":"user","message":{"role":"user","content":"<local-command-stdout>Login successful</local-command-stdout>"}}`,
			`{"type":"last-prompt"}`,
		}},
		{"a /clear-only session has none", false, []string{
			`{"type":"mode"}`, caveat, clearCommand, `{"type":"cost-state"}`,
		}},
		{"a session with a reply has turns", true, []string{
			`{"type":"user","message":{"role":"user","content":"what does this script do?"}}`,
			`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"It lists sessions."}]}}`,
		}},
		{"a prompt interrupted before any reply has turns", true, []string{
			`{"type":"mode"}`, caveat,
			`{"type":"user","message":{"role":"user","content":"start refactoring the cache layer"}}`,
			`{"type":"last-prompt"}`,
		}},
		{"a slash command that did work has turns", true, []string{
			caveat,
			`{"type":"user","message":{"role":"user","content":"<command-name>/review-branch</command-name>\n            <command-args></command-args>"}}`,
			`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Reviewing."}]}}`,
		}},
		{"a structured-array prompt has turns", true, []string{
			`{"type":"mode"}`, caveat,
			`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"look at the build failure"}]}}`,
		}},
		{"a structured-array slash command has none", false, []string{
			caveat,
			`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<command-name>/effort</command-name>\n            <command-args></command-args>"}]}}`,
			`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<local-command-stdout>Set effort level to high</local-command-stdout>"}]}}`,
		}},
		{"an empty transcript has none", false, nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := parse(t, c.lines...).HasTurns; got != c.want {
				t.Errorf("HasTurns = %v, want %v", got, c.want)
			}
		})
	}
}

func TestOpeningPrompt(t *testing.T) {
	cases := []struct {
		name  string
		want  string
		lines []string
	}{
		{"a prompt after /clear is the opening prompt", "How does the masthead get updated?", []string{
			caveat, clearCommand,
			`{"type":"user","message":{"role":"user","content":"How does the masthead get updated?"}}`,
		}},
		{"a skill invocation is shown as typed", "/qtx-logs find the gateway errors", []string{
			caveat, clearCommand,
			`{"type":"user","message":{"role":"user","content":"<command-message>qtx-logs</command-message>\n<command-name>/qtx-logs</command-name>\n<command-args>find the gateway errors</command-args>"}}`,
			`{"type":"user","isMeta":true,"message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /skills/qtx-logs"}]}}`,
		}},
		{"multi-line skill arguments are kept", "/qtx-logs errors in the gateway\n\nsince Tuesday", []string{
			`{"type":"user","message":{"role":"user","content":"<command-name>/qtx-logs</command-name>\n<command-args>errors in the gateway\n\nsince Tuesday</command-args>"}}`,
		}},
		{"a skill invoked without arguments is shown by name", "/wip", []string{
			caveat,
			`{"type":"user","message":{"role":"user","content":"<command-name>/wip</command-name>\n<command-args></command-args>"}}`,
			`{"type":"user","isMeta":true,"message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /skills/wip"}]}}`,
		}},
		{"a local command with output is skipped", "tidy up the cache layer", []string{
			caveat,
			`{"type":"user","message":{"role":"user","content":"<command-name>/model</command-name>\n<command-args></command-args>"}}`,
			`{"type":"user","message":{"role":"user","content":"<local-command-stdout>Set model to opus</local-command-stdout>"}}`,
			`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"tidy up the cache layer"}]}}`,
		}},
		{"a /clear-only session has none", "", []string{caveat, clearCommand}},
		{"a half-written line does not hide it", "first ask", []string{
			`{"type":"user","message":{"role":"user","content":"first ask"}}`,
			`{"type":"user","message":{"role`,
		}},
		{"a half-written line before it does not hide it", "second ask", []string{
			`{"type":"user","message":{"role`,
			`{"type":"user","message":{"role":"user","content":"second ask"}}`,
		}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := parse(t, c.lines...).OpeningPrompt; got != c.want {
				t.Errorf("OpeningPrompt = %q, want %q", got, c.want)
			}
		})
	}
}

func TestFirstUserLineFields(t *testing.T) {
	s := parse(t,
		`{"type":"user","cwd":"/tmp/proj","gitBranch":"main","timestamp":"2026-10-01T09:30:00.000Z","message":{"role":"user","content":"hello"}}`,
		`{"type":"user","cwd":"/elsewhere","gitBranch":"other","message":{"role":"user","content":"again"}}`,
	)
	if s.Cwd != "/tmp/proj" || s.Branch != "main" {
		t.Errorf("cwd, branch = %q, %q, want /tmp/proj, main", s.Cwd, s.Branch)
	}
	if s.Started.IsZero() || s.Started.UTC().Hour() != 9 {
		t.Errorf("Started = %v, want 09:30 UTC", s.Started)
	}
	if s.Project() != "proj" {
		t.Errorf("Project = %q, want proj", s.Project())
	}
}

