func TestTitle(t *testing.T) {
	t.Run("the last ai-title wins", func(t *testing.T) {
		s := parse(t,
			`{"type":"user","message":{"role":"user","content":"hi"}}`,
			`{"type":"ai-title","aiTitle":"First"}`,
			`{"type":"ai-title","aiTitle":"Masthead publishing"}`,
		)
		if s.Title() != "Masthead publishing" {
			t.Errorf("Title = %q", s.Title())
		}
	})
	t.Run("an untitled session is named by its opening prompt's first line", func(t *testing.T) {
		s := parse(t, `{"type":"user","message":{"role":"user","content":"<command-name>/qtx-logs</command-name>\n<command-args>find the gateway errors\nand more</command-args>"}}`)
		if s.Title() != "/qtx-logs find the gateway errors" {
			t.Errorf("Title = %q", s.Title())
		}
	})
	t.Run("with nothing to go on it is untitled", func(t *testing.T) {
		if got := parse(t, caveat, clearCommand).Title(); got != "(untitled)" {
			t.Errorf("Title = %q", got)
		}
	})
}

func TestSearchText(t *testing.T) {
	s := parse(t,
		`{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"How does the masthead get updated when we publish?"}}`,
		`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Looking."}]}}`,
		`{"type":"ai-title","aiTitle":"Masthead publishing"}`,
		`{"type":"summary","summary":"Traced the publish orchestrator"}`,
		`{"type":"last-prompt","lastPrompt":"check the old step"}`,
		`{"type":"last-prompt","lastPrompt":"check the swap\n\tand drop step"}`,
	)
	text := s.SearchText()
	for _, want := range []string{"masthead get updated", "publish orchestrator", "swap and drop"} {
		if !strings.Contains(text, want) {
			t.Errorf("SearchText %q lacks %q", text, want)
		}
	}
	if strings.Contains(text, "old step") {
		t.Errorf("SearchText %q kept an earlier last-prompt", text)
	}
	if s.LastPrompt != "check the swap\n\tand drop step" {
		t.Errorf("LastPrompt = %q", s.LastPrompt)
	}
	if s.Messages != 2 {
		t.Errorf("Messages = %d, want 2", s.Messages)
	}
}

func TestSearchTextIsCapped(t *testing.T) {
	s := parse(t, `{"type":"user","message":{"role":"user","content":"`+strings.Repeat("é", 500)+`"}}`)
	if n := len([]rune(s.SearchText())); n != 400 {
		t.Errorf("SearchText is %d runes, want 400", n)
	}
}

func TestVeryLongLinesAreRead(t *testing.T) {
	huge := `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"` + strings.Repeat("x", 5<<20) + `"}]}}`
	s := parse(t, `{"type":"user","message":{"role":"user","content":"hi"}}`, huge, `{"type":"ai-title","aiTitle":"After the big line"}`)
	if s.Title() != "After the big line" {
		t.Errorf("Title = %q", s.Title())
	}
}
