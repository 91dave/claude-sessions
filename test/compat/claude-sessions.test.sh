#!/bin/bash

set -uo pipefail

# The dotfiles bash suite, run against the Go binary with only the helpers adapted.
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SUT="${CLAUDE_SESSIONS_BIN:?set CLAUDE_SESSIONS_BIN to the binary under test}"
FIXTURES="$(mktemp -d)"
SOCKET="claude-sessions-test-$$"

export PATH="$SELF_DIR/bin:$PATH"
export CLAUDE_SESSIONS_CONFIG="$FIXTURES/config.json"
unset CLAUDE_SESSIONS_DRYRUN CLAUDE_SESSIONS_DEFAULT CLAUDE_SESSIONS_TMUX
cat > "$CLAUDE_SESSIONS_CONFIG" <<'EOF'
{
  "tmux": "auto",
  "commands": {
    "livePane": "agent-state pane {pid}",
    "attach": "agent-state jump {pane}",
    "reviveTmux": "tmux new-session -d -s {tmuxName} -c {cwd} {claude} && tmux-sessions --attach {tmuxName}",
    "previewRunning": "agent-state preview {pane}"
  }
}
EOF

as_picker_rows() {  # reshape --list rows into the bash picker's display, id, cwd, pane
    awk -F'\t' 'BEGIN { OFS = "\t" } { print $2 " " $3 "  " $6 "  " $4 "  " $5 "  " $9, $1, $7, $8 }'
}

PASS=0
FAIL=0

cleanup() {
    command tmux -L "$SOCKET" kill-server 2>/dev/null
    rm -rf "$FIXTURES"
}
trap cleanup EXIT

check() {  # check <name> <expected> <actual>
    if [[ "$2" == "$3" ]]; then
        PASS=$((PASS + 1))
        printf '  ok   %s\n' "$1"
    else
        FAIL=$((FAIL + 1))
        printf '  FAIL %s\n       expected: %q\n       actual:   %q\n' "$1" "$2" "$3"
    fi
}

contains() {  # contains <name> <needle> <haystack>
    if [[ "$3" == *"$2"* ]]; then
        PASS=$((PASS + 1))
        printf '  ok   %s\n' "$1"
    else
        FAIL=$((FAIL + 1))
        printf '  FAIL %s\n       %q not found in: %q\n' "$1" "$2" "$3"
    fi
}

lacks() {  # lacks <name> <needle> <haystack>
    if [[ "$3" != *"$2"* ]]; then
        PASS=$((PASS + 1))
        printf '  ok   %s\n' "$1"
    else
        FAIL=$((FAIL + 1))
        printf '  FAIL %s\n       %q unexpectedly found in: %q\n' "$1" "$2" "$3"
    fi
}

# The caveat line Claude Code injects ahead of every local command run.
CAVEAT='{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}'

fixture() {  # fixture <name>  -- writes stdin to a transcript, echoes its path
    local path="$FIXTURES/$1.jsonl"
    cat > "$path"
    printf '%s' "$path"
}

turns_status() {  # turns_status <transcript-path>  -- 0 has turns, 1 none
    "$SUT" --has-turns "$1" >/dev/null 2>&1
    printf '%d' "$?"
}

echo "has-turns"

f="$(fixture login <<EOF
{"type":"mode"}
$CAVEAT
{"type":"user","message":{"role":"user","content":"<command-name>/login</command-name>\n            <command-message>login</command-message>\n            <command-args></command-args>"}}
{"type":"user","message":{"role":"user","content":"<local-command-stdout>Login successful</local-command-stdout>"}}
{"type":"last-prompt"}
EOF
)"
check "a /login-only session has no turns" "1" "$(turns_status "$f")"

f="$(fixture cleared <<EOF
{"type":"mode"}
$CAVEAT
{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"}}
{"type":"cost-state"}
EOF
)"
check "a /clear-only session has no turns" "1" "$(turns_status "$f")"

f="$(fixture answered <<EOF
{"type":"user","message":{"role":"user","content":"what does this script do?"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"It lists sessions."}]}}
EOF
)"
check "a session with a reply has turns" "0" "$(turns_status "$f")"

f="$(fixture interrupted <<EOF
{"type":"mode"}
$CAVEAT
{"type":"user","message":{"role":"user","content":"start refactoring the cache layer"}}
{"type":"last-prompt"}
EOF
)"
check "a prompt interrupted before any reply has turns" "0" "$(turns_status "$f")"

f="$(fixture command-that-worked <<EOF
$CAVEAT
{"type":"user","message":{"role":"user","content":"<command-name>/review-branch</command-name>\n            <command-args></command-args>"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Reviewing."}]}}
EOF
)"
check "a slash command that did work has turns" "0" "$(turns_status "$f")"

f="$(fixture structured-content <<EOF
{"type":"mode"}
$CAVEAT
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"look at the build failure"}]}}
EOF
)"
check "a structured-array prompt has turns" "0" "$(turns_status "$f")"

f="$(fixture structured-command <<EOF
$CAVEAT
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<command-name>/effort</command-name>\n            <command-args></command-args>"}]}}
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"<local-command-stdout>Set effort level to high</local-command-stdout>"}]}}
EOF
)"
check "a structured-array slash command has no turns" "1" "$(turns_status "$f")"

f="$(fixture no-content </dev/null)"
check "an empty transcript has no turns" "1" "$(turns_status "$f")"

echo "opening prompt"

opening_prompt() {  # opening_prompt <transcript-path>
    "$SUT" --opening-prompt "$1" 2>/dev/null
}

CLEAR='{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"}}'

f="$(fixture cleared-then-asked <<EOF
$CAVEAT
$CLEAR
{"type":"user","message":{"role":"user","content":"How does the masthead get updated?"}}
EOF
)"
check "a prompt after /clear is the opening prompt" "How does the masthead get updated?" "$(opening_prompt "$f")"

f="$(fixture cleared-then-skill <<EOF
$CAVEAT
$CLEAR
{"type":"user","message":{"role":"user","content":"<command-message>qtx-logs</command-message>\n<command-name>/qtx-logs</command-name>\n<command-args>find the gateway errors</command-args>"}}
{"type":"user","isMeta":true,"message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /skills/qtx-logs"}]}}
EOF
)"
check "a skill invocation is shown as typed" "/qtx-logs find the gateway errors" "$(opening_prompt "$f")"

f="$(fixture skill-multiline-args <<EOF
{"type":"user","message":{"role":"user","content":"<command-name>/qtx-logs</command-name>\n<command-args>errors in the gateway\n\nsince Tuesday</command-args>"}}
EOF
)"
check "multi-line skill arguments are kept" "$(printf '/qtx-logs errors in the gateway\n\nsince Tuesday')" "$(opening_prompt "$f")"

f="$(fixture skill-no-args <<EOF
$CAVEAT
{"type":"user","message":{"role":"user","content":"<command-name>/wip</command-name>\n<command-args></command-args>"}}
{"type":"user","isMeta":true,"message":{"role":"user","content":[{"type":"text","text":"Base directory for this skill: /skills/wip"}]}}
EOF
)"
check "a skill invoked without arguments is shown by name" "/wip" "$(opening_prompt "$f")"

f="$(fixture model-then-asked <<EOF
$CAVEAT
{"type":"user","message":{"role":"user","content":"<command-name>/model</command-name>\n<command-args></command-args>"}}
{"type":"user","message":{"role":"user","content":"<local-command-stdout>Set model to opus</local-command-stdout>"}}
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"tidy up the cache layer"}]}}
EOF
)"
check "a local command with output is skipped" "tidy up the cache layer" "$(opening_prompt "$f")"

f="$(fixture only-cleared <<EOF
$CAVEAT
$CLEAR
EOF
)"
check "a /clear-only session has no opening prompt" "" "$(opening_prompt "$f")"

f="$(fixture truncated <<EOF
{"type":"user","message":{"role":"user","content":"first ask"}}
{"type":"user","message":{"role
EOF
)"
check "a half-written line does not hide the opening prompt" "first ask" "$(opening_prompt "$f")"

echo "listing"

CONFIG="$FIXTURES/config"
SHIM="$FIXTURES/shim"
STATE="$FIXTURES/agent-state"
PROJ="$FIXTURES/proj"
mkdir -p "$CONFIG/projects/-tmp-proj" "$CONFIG/sessions" "$SHIM" "$STATE" "$PROJ"

cat > "$SHIM/tmux" <<EOF
#!/bin/bash
exec $(command -v tmux) -L "$SOCKET" "\$@"
EOF
chmod +x "$SHIM/tmux"

transcript() {  # transcript <id>  -- a turn-less session under the isolated config
    cat > "$CONFIG/projects/-tmp-proj/$1.jsonl" <<EOF
$CAVEAT
{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"<command-name>/login</command-name>"}}
EOF
}

listing() {  # listing  -- rows the picker would show, cache discarded each time
    rm -rf "$FIXTURES/cache"
    env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" XDG_CACHE_HOME="$FIXTURES/cache" \
        XDG_DATA_HOME="$FIXTURES/data" AGENT_STATE_DIR="$STATE" "$SUT" --list 2>/dev/null | as_picker_rows
}

DEAD=aaaaaaaa-0000-0000-0000-00000000dead
transcript "$DEAD"
check "a turn-less session is left out of the listing" "0" "$(listing | wc -l)"

printf '{"sessionId":"%s","pid":%d,"cwd":"/tmp/proj"}\n' "$DEAD" "$$" > "$CONFIG/sessions/live.json"
check "a turn-less session still live is kept" "1" "$(listing | wc -l)"
check "and is marked live" "1" "$(listing | cut -f1 | grep -c '●')"

rm -f "$CONFIG/sessions/live.json"
printf '{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"hi"}]}}\n' \
    >> "$CONFIG/projects/-tmp-proj/$DEAD.jsonl"
check "a session that gained a turn comes back" "1" "$(listing | wc -l)"

SKILLED=bbbbbbbb-0000-0000-0000-0000000skill
cat > "$CONFIG/projects/-tmp-proj/$SKILLED.jsonl" <<EOF
$CAVEAT
{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"<command-name>/clear</command-name>\n<command-args></command-args>"}}
{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"<command-name>/qtx-logs</command-name>\n<command-args>find the gateway errors</command-args>"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Searching."}]}}
EOF
contains "an untitled session is listed by the skill it opened with" \
    "/qtx-logs find the gateway errors" "$(listing | rg -F "$SKILLED")"

out="$(env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" AGENT_STATE_DIR="$STATE" \
    XDG_CACHE_HOME="$FIXTURES/cache" "$SUT" --preview "$SKILLED" /tmp/proj 2>&1)"
contains "and previewed with it as the opening prompt" "/qtx-logs find the gateway errors" "$out"
lacks "not the command caveat" "local-command-caveat" "$out"
rm -f "$CONFIG/projects/-tmp-proj/$SKILLED.jsonl"

echo "search text"

MASTHEAD=cccccccc-0000-0000-0000-00000masthead
GATEWAY=dddddddd-0000-0000-0000-000000gateway
cat > "$CONFIG/projects/-tmp-proj/$MASTHEAD.jsonl" <<EOF
{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"How does the masthead get updated when we publish?"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Looking."}]}}
{"type":"ai-title","aiTitle":"Masthead publishing"}
{"type":"summary","summary":"Traced the publish orchestrator"}
{"type":"last-prompt","lastPrompt":"check the swap and drop step"}
EOF
cat > "$CONFIG/projects/-tmp-proj/$GATEWAY.jsonl" <<EOF
{"type":"user","cwd":"/tmp/proj","gitBranch":"main","message":{"role":"user","content":"<command-name>/qtx-logs</command-name>\n<command-args>gateway errors</command-args>"}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Searching."}]}}
EOF

row="$(listing | rg -F "$MASTHEAD" | cut -f1)"
contains "a row can be found by its opening prompt" "masthead get updated" "$row"
contains "by where it left off" "swap and drop" "$row"
contains "and by its compaction summary" "publish orchestrator" "$row"

echo "ask"

cat > "$SHIM/claude" <<EOF
#!/bin/bash
printf '%s\n' "\$@" > "$FIXTURES/claude-args"
cat > "$FIXTURES/claude-stdin"
[[ -n "\${STUB_CLAUDE_FAIL:-}" ]] && exit 1
printf '%b' "\${STUB_CLAUDE_REPLY:-}"
EOF
chmod +x "$SHIM/claude"

asking() {  # asking <question> [reply]  -- rows the ask mode would show
    rm -rf "$FIXTURES/cache"
    env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" XDG_CACHE_HOME="$FIXTURES/cache" \
        XDG_DATA_HOME="$FIXTURES/data" AGENT_STATE_DIR="$STATE" STUB_CLAUDE_REPLY="${2:-}" \
        "$SUT" --ask "$1" 2>/dev/null | as_picker_rows
}

out="$(asking "where did the header publishing go" "$GATEWAY\nnot-a-session\n$MASTHEAD\n$GATEWAY\n")"
check "sessions come back in the order Claude ranked them" "$GATEWAY $MASTHEAD" "$(cut -f2 <<<"$out" | xargs)"
contains "the question is sent to Claude" "where did the header publishing go" "$(cat "$FIXTURES/claude-stdin")"
contains "with each session's details" "swap and drop" "$(cat "$FIXTURES/claude-stdin")"
contains "without saving the ranking call as a session" "--no-session-persistence" "$(cat "$FIXTURES/claude-args")"

out="$(asking "nothing like this" "")"
check "no matches gives a single row" "1" "$(wc -l <<<"$out")"
contains "that says so" "no matching sessions" "$out"
check "and cannot be resumed" "" "$(cut -f2 <<<"$out")"

out="$(STUB_CLAUDE_FAIL=1 asking "anything")"
contains "a failed call says so" "ask failed" "$out"
check "in a row that cannot be resumed" "" "$(cut -f2 <<<"$out")"

rm -f "$CONFIG/projects/-tmp-proj/$MASTHEAD.jsonl" "$CONFIG/projects/-tmp-proj/$GATEWAY.jsonl"

# The fzf "modes" checks have no equivalent here: the TUI model tests in internal/tui cover them.

echo "jump"

live_marker() {  # live_marker <id> [tmux target] [pid]  -- the marker a running session writes
    rm -f "$CONFIG/sessions"/*.json
    printf '{"sessionId":"%s","pid":%d,"cwd":"%s"%s}\n' "$1" "${3:-$$}" "$PROJ" \
        "${2:+,\"tmux\":\"$2\"}" > "$CONFIG/sessions/$$.json"
}

jumping() {  # jumping <key> <id>  -- what the picker would do, without doing it
    env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" CLAUDE_SESSIONS_DRYRUN=1 \
        XDG_DATA_HOME="$FIXTURES/data" "$SUT" --jump-action "$1" "$2" "$PROJ" 2>&1
}

rm -f "$CONFIG/sessions/live.json"
out="$(jumping enter "$DEAD")"
contains "a session that is not running gets a fresh tmux session" \
    "tmux new-session -d -s cc-proj -c $PROJ" "$out"
contains "resumed in it" "claude --resume $DEAD" "$out"
contains "and attached to" "tmux-sessions --attach cc-proj" "$out"

env PATH="$SHIM:$PATH" tmux new-session -d -s cc-live 'sleep 600'
PANE="$(env PATH="$SHIM:$PATH" tmux list-panes -t '=cc-live' -F '#{pane_id}' | head -1)"
live_marker "$DEAD" "cc-live:@0.$PANE"
check "a running session is jumped to in the pane it is running in" \
    "agent-state jump $PANE" "$(jumping enter "$DEAD")"

contains "forking a running session still opens a fresh one" "--fork-session" \
    "$(jumping alt-enter "$DEAD")"

live_marker "$DEAD" "cc-live:@0.%999"
out="$(jumping enter "$DEAD")"
contains "a running session whose pane has gone is refused" "already running" "$out"
lacks "rather than resumed a second time" "claude --resume" "$out"

live_marker "$DEAD"
out="$(jumping enter "$DEAD")"
contains "so is one running outside tmux" "already running" "$out"
lacks "which is not resumed either" "claude --resume" "$out"

sleep 0 & EXITED=$!
wait "$EXITED"
live_marker "$DEAD" "cc-live:@0.$PANE" "$EXITED"
contains "a marker left by a process that has exited is resumed" \
    "claude --resume $DEAD" "$(jumping enter "$DEAD")"

live_marker "$DEAD" "cc-live:@0.$PANE"
printf '{"sessionId":"half-writ' > "$CONFIG/sessions/0.json"
check "a half-written marker does not hide a running session" \
    "agent-state jump $PANE" "$(jumping enter "$DEAD")"
rm -f "$CONFIG/sessions/0.json"

echo "resume"

resuming() {  # resuming <key> <id>  -- what the plain picker would do
    env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" CLAUDE_SESSIONS_DRYRUN=1 \
        XDG_DATA_HOME="$FIXTURES/data" "$SUT" --action "$1" "$2" "$PROJ" 2>&1
}

live_marker "$DEAD" "cc-live:@0.$PANE"
check "the plain picker jumps to a running session too" \
    "agent-state jump $PANE" "$(resuming enter "$DEAD")"
contains "but still forks it on request" "--fork-session" "$(resuming alt-enter "$DEAD")"

live_marker "$DEAD"
contains "and refuses one running outside tmux" "already running" "$(resuming enter "$DEAD")"

rm -f "$CONFIG/sessions"/*.json
contains "a session that is not running is resumed" \
    "claude --resume $DEAD" "$(resuming enter "$DEAD")"

echo "cc"

guarding() {  # guarding <claude args...>  -- the running session they would reopen, and the exit status
    local out
    out="$(env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" "$SUT" --resumes-running "$@" 2>&1)"
    printf '%s:%d' "$out" "$?"
}

live_marker "$DEAD" "cc-live:@0.$PANE"
check "cc --resume on a running session names it" "$DEAD:0" "$(guarding --resume "$DEAD")"
check "as does -r" "$DEAD:0" "$(guarding --model opus -r "$DEAD")"
check "and --resume=<id>" "$DEAD:0" "$(guarding "--resume=$DEAD")"
check "but not when it forks" ":1" "$(guarding --resume "$DEAD" --fork-session)"
check "nor a plain cc" ":1" "$(guarding --model opus)"
check "nor a --resume that opens the picker" ":1" "$(guarding --resume)"

check "cc is sent to the pane it is running in" "agent-state jump $PANE" \
    "$(env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" CLAUDE_SESSIONS_DRYRUN=1 \
        "$SUT" --attach-running "$DEAD" 2>&1)"

rm -f "$CONFIG/sessions"/*.json
check "cc --resume on a session that is not running goes ahead" ":1" "$(guarding --resume "$DEAD")"

echo "live preview"


agent_file() {  # agent_file <state> <pane>  -- what the agent's hooks record
    printf '%s\n%s\n%s\n' "$1" "$2" "$PROJ" > "$STATE/$$"
}

previewing() {  # previewing [pane]
    env PATH="$SHIM:$PATH" CLAUDE_CONFIG_DIR="$CONFIG" AGENT_STATE_DIR="$STATE" \
        XDG_CACHE_HOME="$FIXTURES/cache" "$SUT" --preview "$DEAD" "$PROJ" "${1:-}" 2>&1
}

env PATH="$SHIM:$PATH" tmux new-session -d -s cc-preview 'echo SENTINEL-PANE; sleep 600'
PPANE="$(env PATH="$SHIM:$PATH" tmux list-panes -t '=cc-preview' -F '#{pane_id}' | head -1)"

out="$(previewing "$PPANE")"
contains "a live pane is shown instead of the transcript" "SENTINEL-PANE" "$out"
lacks "so the transcript sections are left out" "Opening prompt" "$out"

contains "a session with no pane still reads from its transcript" "Opening prompt" \
    "$(previewing)"
contains "and so does one whose pane has gone" "Opening prompt" "$(previewing %999)"

agent_file working "$PPANE"
live_marker "$DEAD"
check "a live session with an agent state file offers its pane to the picker" \
    "$PPANE" "$(listing | cut -f4)"

rm -f "$STATE/$$"
check "one without an agent state file offers none" "" "$(listing | cut -f4)"

agent_file working "%999"
check "nor does one whose pane has gone" "" "$(listing | cut -f4)"

agent_file working "$PPANE"
rm -f "$CONFIG/sessions"/*.json
check "nor does a session that is not running" "" "$(listing | cut -f4)"

echo
printf '%d passed, %d failed\n' "$PASS" "$FAIL"
[[ $FAIL -eq 0 ]]
